# SISTEMA DE CONTROL DE ACCESO PARA ESTACIONAMIENTO DE MAESTROS
# Proyecto Tecnologías II

import datetime
import time

# ----------------- CONFIGURACIÓN INICIAL -----------------

CAPACIDAD_TOTAL = 10

# Lista de UIDs autorizados (tarjetas de maestros)
# En la vida real, estos se leerían desde una base de datos o EEPROM
TARJETAS_AUTORIZADAS = [
    "A1B2C3D4",  # Maestro: Juan Pérez
    "E5F6G7H8",  # Maestra: María García
    "I9J0K1L2",  # Maestro: Carlos Rodríguez
    "M3N4O5P6",  # Maestra: Ana Martínez
    "Q7R8S9T0"   # Maestro: Luis Fernández
]

# Diccionario para relacionar UID con nombre del maestro
BASE_DATOS_MAESTROS = {
    "A1B2C3D4": "Juan Pérez",
    "E5F6G7H8": "María García",
    "I9J0K1L2": "Carlos Rodríguez",
    "M3N4O5P6": "Ana Martínez",
    "Q7R8S9T0": "Luis Fernández"
}

# Estado del estacionamiento
estado_estacionamiento = {
    "lugares_ocupados": 0,
    "lugares_disponibles": CAPACIDAD_TOTAL,
    "pluma_levantada": False,
    "ultimo_acceso": None,
    "historial_accesos": []
}

# FUNCIONES PRINCIPALES DEL SISTEMA

def leer_tarjeta(uid_simulado=None):
    """
    Simula la lectura de una tarjeta NFC.

    Parámetros:
        uid_simulado (str): UID de la tarjeta (para pruebas). Si es None, simula una lectura manual.

    Retorna:
        str: UID de la tarjeta leída, o None si no se detectó ninguna.

    NOTA: En el hardware real, esta función interactuaría con el lector NFC vía I2C/SPI.
    """
    if uid_simulado:
        return uid_simulado

    uid = input("🔑 Coloca la tarjeta cerca del lector (simulado): ").strip().upper()
    return uid if uid else None


def validar_acceso(uid):
    """
    Verifica si el UID proporcionado está autorizado para ingresar.

    Parámetros:
        uid (str): UID de la tarjeta a validar.

    Retorna:
        tuple: (bool, str) - (True/False, nombre del maestro o mensaje de error)
    """
    if uid in TARJETAS_AUTORIZADAS:
        nombre = BASE_DATOS_MAESTROS.get(uid, "Maestro desconocido")
        return True, nombre
    else:
        return False, "❌ Acceso denegado: Tarjeta no autorizada"


def contar_vehiculos():
    """
    Simula la lectura de los sensores de presencia y ultrasónico para
    determinar cuántos lugares están ocupados.

    Retorna:
        int: Número de vehículos actualmente en el estacionamiento.

    NOTA: En hardware real, se usarían los sensores de entrada/salida
    para incrementar/decrementar el contador.
    """
    return estado_estacionamiento["lugares_ocupados"]


def actualizar_display():
    """
    Actualiza la información mostrada en el display LCD.
    Muestra lugares disponibles o mensaje de "COMPLETO".

    Retorna:
        str: Mensaje que se mostraría en el display.

    NOTA: En hardware real, se enviaría el mensaje al display vía I2C.
    """
    ocupados = estado_estacionamiento["lugares_ocupados"]
    disponibles = CAPACIDAD_TOTAL - ocupados

    if disponibles > 0:
        mensaje = f"🚗 Lugares disponibles: {disponibles}/{CAPACIDAD_TOTAL}"
    else:
        mensaje = "🚫 ESTACIONAMIENTO COMPLETO"

    print(f"[DISPLAY] {mensaje}")
    return mensaje


def controlar_pluma(levantar=True):
    """
    Controla el motor servo para levantar o bajar la pluma de cartón.

    Parámetros:
        levantar (bool): True para levantar la pluma, False para bajarla.

    Retorna:
        str: Estado actual de la pluma.

    NOTA: En hardware real, se enviaría la señal PWM al servo.
    """
    if levantar:
        estado_estacionamiento["pluma_levantada"] = True
        estado = "🟢 PLUMA LEVANTADA - Acceso permitido"
    else:
        estado_estacionamiento["pluma_levantada"] = False
        estado = "🔴 PLUMA BAJADA - Acceso bloqueado"

    print(f"[SERVO] {estado}")
    return estado


def registrar_evento(uid, nombre, tipo, exitoso):
    """
    Registra un evento de entrada o salida en el historial del sistema.

    Parámetros:
        uid (str): UID de la tarjeta.
        nombre (str): Nombre del maestro.
        tipo (str): "ENTRADA" o "SALIDA".
        exitoso (bool): True si el acceso fue exitoso.
    """
    evento = {
        "uid": uid,
        "maestro": nombre,
        "fecha_hora": datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "tipo": tipo,
        "exitoso": exitoso
    }
    estado_estacionamiento["historial_accesos"].append(evento)
    estado_estacionamiento["ultimo_acceso"] = evento
    print(f"[REGISTRO] {tipo} registrada para {nombre} - {'✅ Exitosa' if exitoso else '❌ Fallida'}")


def procesar_entrada(uid):
    """
    Procesa la entrada de un vehículo al estacionamiento.

    Parámetros:
        uid (str): UID de la tarjeta.

    Retorna:
        bool: True si el acceso fue concedido, False en caso contrario.
    """
    autorizado, nombre = validar_acceso(uid)

    if not autorizado:
        registrar_evento(uid, "DESCONOCIDO", "ENTRADA", False)
        print(f"⛔ {nombre}")
        return False

    if estado_estacionamiento["lugares_ocupados"] >= CAPACIDAD_TOTAL:
        print("🚫 No hay lugares disponibles")
        registrar_evento(uid, nombre, "ENTRADA", False)
        return False

    estado_estacionamiento["lugares_ocupados"] += 1
    estado_estacionamiento["lugares_disponibles"] = CAPACIDAD_TOTAL - estado_estacionamiento["lugares_ocupados"]

    controlar_pluma(levantar=True)
    time.sleep(1)  # Simula tiempo para que el vehículo pase
    controlar_pluma(levantar=False)

    registrar_evento(uid, nombre, "ENTRADA", True)
    actualizar_display()

    print(f"✅ Acceso concedido a {nombre}")
    return True


def procesar_salida(uid=None):
    """
    Procesa la salida de un vehículo del estacionamiento.
    En la simulación, no requiere UID (se asume que sale un vehículo).

    Parámetros:
        uid (str, opcional): UID de la tarjeta para registro.

    Retorna:
        bool: True si la salida fue procesada correctamente.
    """
    if estado_estacionamiento["lugares_ocupados"] <= 0:
        print("⚠️ No hay vehículos para salir")
        return False

    estado_estacionamiento["lugares_ocupados"] -= 1
    estado_estacionamiento["lugares_disponibles"] = CAPACIDAD_TOTAL - estado_estacionamiento["lugares_ocupados"]

    controlar_pluma(levantar=True)
    time.sleep(1)
    controlar_pluma(levantar=False)

    nombre = "Salida"
    registrar_evento(uid or "SALIDA", nombre, "SALIDA", True)
    actualizar_display()

    print(f"✅ Salida procesada. Lugares ocupados: {estado_estacionamiento['lugares_ocupados']}")
    return True


def ver_historial():
    """
    Muestra el historial completo de accesos del sistema.
    """
    print("\n" + "=" * 60)
    print("📋 HISTORIAL DE ACCESOS")
    print("=" * 60)

    if not estado_estacionamiento["historial_accesos"]:
        print("No hay registros aún.")
        return

    for evento in estado_estacionamiento["historial_accesos"]:
        status = "✅" if evento["exitoso"] else "❌"
        print(f"{evento['fecha_hora']} | {evento['tipo']:7} | {evento['maestro']:15} | {status}")

    print("=" * 60)


def reiniciar_sistema():
    """
    Reinicia el estado del estacionamiento (función administrativa).
    """
    global estado_estacionamiento
    estado_estacionamiento["lugares_ocupados"] = 0
    estado_estacionamiento["lugares_disponibles"] = CAPACIDAD_TOTAL
    estado_estacionamiento["pluma_levantada"] = False
    print("🔄 Sistema reiniciado correctamente")
    actualizar_display()


def generar_reporte():
    """
    Genera un reporte completo del estado actual del sistema.
    Útil para el administrador.
    """
    print("\n" + "=" * 60)
    print("📊 REPORTE DEL SISTEMA DE ESTACIONAMIENTO")
    print("=" * 60)
    print(f"📅 Fecha y hora: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    print(f"🏢 Capacidad total: {CAPACIDAD_TOTAL} lugares")
    print(f"🚗 Lugares ocupados: {estado_estacionamiento['lugares_ocupados']}")
    print(f"🟢 Lugares disponibles: {estado_estacionamiento['lugares_disponibles']}")
    print(f"🚧 Pluma: {'🟢 LEVANTADA' if estado_estacionamiento['pluma_levantada'] else '🔴 BAJADA'}")
    print(f"👤 Último acceso: {estado_estacionamiento['ultimo_acceso']}")
    print(f"📋 Total de eventos registrados: {len(estado_estacionamiento['historial_accesos'])}")
    print("=" * 60)

    print("\n📇 TARJETAS AUTORIZADAS:")
    for uid, nombre in BASE_DATOS_MAESTROS.items():
        print(f"   🔑 {uid} → {nombre}")
    print("=" * 60)


# DEMOSTRACIÓN DEL SISTEMA

print("=" * 60)
print("🚗 SISTEMA DE ESTACIONAMIENTO - DEMOSTRACIÓN")
print("=" * 60)
print(f"Capacidad total: {CAPACIDAD_TOTAL} lugares")
print(f"Tarjetas registradas: {len(TARJETAS_AUTORIZADAS)}")
print("=" * 60)

# 1. Mostrar estado inicial
actualizar_display()

print("\n" + "-" * 40)
print("🔄 SIMULACIÓN DE ENTRADAS")
print("-" * 40)

# 2. Simular entradas con tarjetas autorizadas
for uid in TARJETAS_AUTORIZADAS[:3]:  # Probamos con las primeras 3 tarjetas
    print(f"\n--- Intentando entrada con UID: {uid} ---")
    procesar_entrada(uid)
    time.sleep(0.5)

# 3. Mostrar estado después de entradas
print("\n" + "-" * 40)
print("📊 ESTADO ACTUAL")
print("-" * 40)
print(f"Lugares ocupados: {estado_estacionamiento['lugares_ocupados']}")
print(f"Lugares disponibles: {estado_estacionamiento['lugares_disponibles']}")

# 4. Intentar entrada con tarjeta no autorizada
print("\n" + "-" * 40)
print("🚫 PRUEBA DE TARJETA NO AUTORIZADA")
print("-" * 40)
print("\n--- Intentando entrada con UID: Z9Y8X7W6 (no autorizada) ---")
procesar_entrada("Z9Y8X7W6")

# 5. Simular salidas
print("\n" + "-" * 40)
print("🔄 SIMULACIÓN DE SALIDAS")
print("-" * 40)
for i in range(2):
    print(f"\n--- Procesando salida {i + 1} ---")
    procesar_salida()
    time.sleep(0.5)

# 6. Ver historial
ver_historial()

# 7. Estado final
print("\n" + "-" * 40)
print("📊 ESTADO FINAL")
print("-" * 40)
actualizar_display()

# 8. Reporte del sistema
generar_reporte()

